--Все издания с их поставщиками
SELECT 
    и.ШифрКниги,
    и.Название,
    и.Автор,
    п.Поставщик,
    п.ДатаПоступление
FROM Издание и
JOIN Поступление п ON и.ИдПоступления = п.ИдПоступления
ORDER BY п.ДатаПоступление DESC;

--Активные выдачи (не возвращённые)
SELECT 
    в.ИдВыдачи,
    ч.ФИО AS Читатель,
    и.Название AS Книга,
    в.ДатаВыдачи,
    в.ПлановыйВозврат,
    DATEDIFF(DAY, в.ПлановыйВозврат, GETDATE()) AS ДнейПросрочки
FROM Выдача в
JOIN Читатель ч ON в.НомБилета = ч.НомБилета
JOIN Издание и ON в.ШифрКниги = и.ШифрКниги
WHERE в.ФактВозврат = 'Нет'
ORDER BY ДнейПросрочки DESC;

--Должники (просроченные выдачи)
SELECT 
    ч.ФИО,
    ч.Телефон,
    COUNT(*) AS ПросроченныхКниг
FROM Выдача в
JOIN Читатель ч ON в.НомБилета = ч.НомБилета
WHERE в.ФактВозврат = 'Нет' 
  AND в.ПлановыйВозврат < GETDATE()
GROUP BY ч.ФИО, ч.Телефон
ORDER BY ПросроченныхКниг DESC;

--Топ-10 самых популярных книг
SELECT TOP 10
    и.Название,
    и.Автор,
    COUNT(*) AS КоличествоВыдач
FROM Выдача в
JOIN Издание и ON в.ШифрКниги = и.ШифрКниги
GROUP BY и.Название, и.Автор
ORDER BY КоличествоВыдач DESC;

--Распределение изданий по категориям
SELECT 
    Категория,
    COUNT(*) AS КоличествоИзданий,
    SUM(CASE WHEN Статус = 'В фонде' THEN 1 ELSE 0 END) AS ВФонде,
    SUM(CASE WHEN Статус = 'Выдано' THEN 1 ELSE 0 END) AS Выдано,
    SUM(CASE WHEN Статус = 'Списано' THEN 1 ELSE 0 END) AS Списано
FROM Издание
GROUP BY Категория
ORDER BY КоличествоИзданий DESC;

--Активность сотрудников (сколько выдач оформил каждый)
SELECT 
    с.ФИО,
    с.Должность,
    COUNT(в.ИдВыдачи) AS ОформленоВыдач
FROM Сотрудник с
LEFT JOIN Выдача в ON с.ИдСотрудника = в.ИдСотрудника
GROUP BY с.ФИО, с.Должность
ORDER BY ОформленоВыдач DESC;

--Читатели с максимальным числом книг на руках (оконная функция)
SELECT 
    ч.ФИО,
    COUNT(*) AS КнигНаРуках,
    RANK() OVER (ORDER BY COUNT(*) DESC) AS Ранг
FROM Выдача в
JOIN Читатель ч ON в.НомБилета = ч.НомБилета
WHERE в.ФактВозврат = 'Нет'
GROUP BY ч.ФИО;